# Embeds the tally's web assets into the firmware as gzipped byte arrays (ATEM_tally_light/web_assets.h):
#   tools/tally_panel.html -> TALLY_PANEL_HTML_GZ, served at /tallies
#   tools/tally_style.css  -> TALLY_STYLE_CSS_GZ,  served at /style.css
#
# Runs automatically before each PlatformIO build (extra_scripts = pre:...).
# Can also be run by hand: python3 pio_scripts/embed_panel.py
# The generated header is committed, so Arduino IDE builds work without this script.
import gzip
import os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ASSETS = [
    ("tools/tally_panel.html", "TALLY_PANEL_HTML_GZ"),
    ("tools/tally_style.css", "TALLY_STYLE_CSS_GZ"),
]
TARGET = os.path.join(PROJECT_DIR, "ATEM_tally_light", "web_assets.h")


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return (
        "const size_t %s_LEN = %d;\n"
        "const uint8_t %s[] PROGMEM = {\n%s\n};\n"
    ) % (name, len(data), name, "\n".join(lines))


def generate():
    parts = [
        "// Generated by pio_scripts/embed_panel.py - do not edit by hand.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
    ]
    sizes = []
    for source, name in ASSETS:
        with open(os.path.join(PROJECT_DIR, source), "rb") as f:
            data = gzip.compress(f.read(), compresslevel=9, mtime=0)  # mtime=0 keeps output reproducible
        parts.append("\n// %s\n%s" % (source, c_array(name, data)))
        sizes.append("%s %d B" % (os.path.basename(source), len(data)))
    header = "".join(parts)

    old = None
    if os.path.exists(TARGET):
        with open(TARGET, "r") as f:
            old = f.read()
    if old != header:  # only touch the file when it changed, to avoid needless rebuilds
        with open(TARGET, "w") as f:
            f.write(header)
        print("embed_panel: updated %s (gzipped: %s)" % (os.path.relpath(TARGET, PROJECT_DIR), ", ".join(sizes)))


generate()
